void UK2Node_CSharpMemberBase::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	const auto NodeClass = GetClass();

	if (!ActionRegistrar.IsOpenForRegistration(NodeClass) || IsRunningCommandlet())
	{
		return;
	}

	WithScriptDomain([this, NodeClass, &ActionRegistrar]
	{
		FCSharpBlueprintMemberLibrary::ForEachOverrideClass([this, NodeClass, &ActionRegistrar](
			FClassReflection* InClassReflection)
			{
				const auto FoundOwnerClass = FCSharpBlueprintMemberLibrary::FindOwnerClass(InClassReflection);

				if (FoundOwnerClass == nullptr)
				{
					return;
				}

				FCSharpBlueprintMemberLibrary::ForEachBlueprintMember(
					InClassReflection, FoundOwnerClass,
					[this, NodeClass, FoundOwnerClass, &ActionRegistrar](const FCSharpBlueprintMemberInfo& InInfo)
					{
						if (!HandlesMemberKind(InInfo.Kind))
						{
							return;
						}

						const auto SpawnData = MakeSpawnData(InInfo);

						const auto Spawner = UBlueprintNodeSpawner::Create(
							NodeClass, nullptr,
							UBlueprintNodeSpawner::FCustomizeNodeDelegate::CreateStatic(
								&UK2Node_CSharpMemberBase::CustomizeNewNode, SpawnData));

						// 模板节点尚未生成，菜单显示信息直接由 SpawnData 推导
						auto& MenuSignature = Spawner->DefaultMenuSignature;

						MenuSignature.MenuName = FText::FromString(GetMenuNameForSpawnData(SpawnData));

						MenuSignature.Category = FText::FromString(FString::Printf(
							TEXT("C#|%s"),
							!SpawnData.Category.IsEmpty()
								? *SpawnData.Category
								: *FoundOwnerClass->GetDisplayNameText().ToString()));

						MenuSignature.Tooltip = !SpawnData.ToolTip.IsEmpty()
							                        ? FText::FromString(SpawnData.ToolTip)
							                        : FText::Format(
								                        LOCTEXT("DefaultTooltip", "访问 C# 类 {0} 的成员 {1}"),
								                        FoundOwnerClass->GetDisplayNameText(),
								                        FText::FromName(SpawnData.MemberName));

						MenuSignature.Keywords = FText::FromString(
							FString::Printf(TEXT("%s C# CSharp"), *SpawnData.MemberName.ToString()));

						ActionRegistrar.AddBlueprintAction(NodeClass, Spawner);
					});
			});
	});
}

bool UK2Node_CSharpMemberBase::IsActionFilteredOut(FBlueprintActionFilter const& Filter)
{
	if (OwnerClass == nullptr)
	{
		return true;
	}

	if (Filter.TargetClasses.IsEmpty())
	{
		return false;
	}

	const auto AuthoritativeOwnerClass = OwnerClass->GetAuthoritativeClass();

	for (const auto& ClassData : Filter.TargetClasses)
	{
		if (ClassData.TargetClass != nullptr &&
			ClassData.TargetClass->GetAuthoritativeClass()->IsChildOf(AuthoritativeOwnerClass))
		{
			return false;
		}
	}

	return true;
}

void UK2Node_CSharpMemberBase::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	if (OwnerClass == nullptr)
	{
		MessageLog.Error(*FText::Format(LOCTEXT("OwnerClassMissing", "@@ 引用的 C# 成员 {0} 所属类无法加载"),
		                                FText::FromName(MemberName)).ToString(), this);

		return;
	}

	auto bDomainReady = false;

	WithScriptDomain([&bDomainReady]
	{
		bDomainReady = true;
	});

	if (!bDomainReady)
	{
		MessageLog.Note(*LOCTEXT("DomainNotReady", "C# 运行时未就绪，@@ 使用缓存签名编译").ToString(), this);

		return;
	}

	FCSharpBlueprintMemberInfo Info;

	if (!ResolveMember(Info))
	{
		MessageLog.Error(*FText::Format(LOCTEXT("MemberMissing", "在 C# 类 {0} 中找不到可供蓝图访问的成员 {1} (@@)"),
		                                GetOwnerClassDisplayName(), FText::FromName(MemberName)).ToString(), this);

		return;
	}

	TArray<FCSharpBlueprintPinDescription> ReflectedPins;

	uint32 Hash{};

	auto bPure = false;

	if (!BuildPinDescriptions(Info, ReflectedPins, Hash, bPure))
	{
		MessageLog.Error(*LOCTEXT("UnsupportedSignature", "@@ 的 C# 签名包含蓝图不支持的类型").ToString(), this);

		return;
	}

	if (Hash != SignatureHash || ReflectedPins != CachedPins || bPure != bIsPure || Info.GetParamCount() != ParamCount)
	{
		MessageLog.Error(*LOCTEXT("SignatureChanged", "@@ 的引脚与当前 C# 签名不一致，请在节点上右键 Refresh Nodes 后重新编译").
		                 ToString(), this);
	}
}

void UK2Node_CSharpMemberBase::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const auto Schema = CompilerContext.GetSchema();

	TArray<UEdGraphPin*> MemberPins;

	GetMemberPins(MemberPins);

	// 未连接的 ref / 容器输入：编译器无法为其生成可寻址的字面量，这里补一个临时变量（等价于 AutoCreateRefTerm）
	for (const auto Pin : MemberPins)
	{
		if (Pin->Direction != EGPD_Input || Pin->LinkedTo.Num() > 0)
		{
			continue;
		}

		if (!Pin->PinType.bIsReference && !Pin->PinType.IsContainer())
		{
			continue;
		}

		const auto TemporaryVariable = CompilerContext.SpawnIntermediateNode<UK2Node_TemporaryVariable>(
			this, SourceGraph);

		TemporaryVariable->VariableType = Pin->PinType;

		TemporaryVariable->VariableType.bIsReference = false;

		TemporaryVariable->AllocateDefaultPins();

		const auto bHasDefaultValue = !Pin->PinType.IsContainer() &&
		(!Pin->DefaultValue.IsEmpty() || Pin->DefaultObject != nullptr || !Pin->DefaultTextValue.IsEmpty());

		if (!bHasDefaultValue)
		{
			if (!Schema->TryCreateConnection(TemporaryVariable->GetVariablePin(), Pin))
			{
				CompilerContext.MessageLog.Error(*LOCTEXT("TempVarConnectFailed", "无法为 @@ 创建临时变量").ToString(),
				                                 Pin);
			}

			continue;
		}

		const auto Assignment = CompilerContext.SpawnIntermediateNode<UK2Node_PureAssignmentStatement>(
			this, SourceGraph);

		Assignment->AllocateDefaultPins();

		const auto bVariableConnected = Schema->TryCreateConnection(Assignment->GetVariablePin(),
		                                                            TemporaryVariable->GetVariablePin());

		const auto bDefaultMoved = CompilerContext.MovePinLinksToIntermediate(*Pin, *Assignment->GetValuePin()).
		                                           CanSafeConnect();

		const auto bOutputConnected = Schema->TryCreateConnection(Assignment->GetOutputPin(), Pin);

		if (!bVariableConnected || !bDefaultMoved || !bOutputConnected)
		{
			CompilerContext.MessageLog.Error(*LOCTEXT("TempVarAssignFailed", "无法为 @@ 赋默认值").ToString(), Pin);
		}
	}
}

