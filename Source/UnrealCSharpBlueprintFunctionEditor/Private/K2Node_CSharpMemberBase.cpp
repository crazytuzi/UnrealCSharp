bool FCSharpBlueprintPinDescription::operator==(const FCSharpBlueprintPinDescription& InOther) const
{
	return PinName == InOther.PinName && Direction == InOther.Direction && PinType == InOther.PinType;
}

void UK2Node_CSharpMemberBase::AllocateDefaultPins()
{
	RefreshFromReflection();

	const auto K2Schema = GetDefault<UEdGraphSchema_K2>();

	if (!IsNodePure())
	{
		CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);

		CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);
	}

	const auto Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this);

	if (OwnerClass != nullptr && Blueprint != nullptr && Blueprint->GeneratedClass == OwnerClass)
	{
		CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UEdGraphSchema_K2::PSC_Self, nullptr,
		          UEdGraphSchema_K2::PN_Self);
	}
	else
	{
		CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object,
		          OwnerClass != nullptr ? OwnerClass.Get() : UObject::StaticClass(), UEdGraphSchema_K2::PN_Self);
	}

	for (const auto& Description : CachedPins)
	{
		const auto Pin = CreatePin(Description.Direction, Description.PinType, Description.PinName);

		Pin->PinToolTip = Description.ToolTip;

		if (Description.Direction == EGPD_Input)
		{
			K2Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
		}
	}

	Super::AllocateDefaultPins();
}

