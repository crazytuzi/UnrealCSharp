bool UK2Node_CSharpMemberBase::HasExternalDependencies(TArray<UStruct*>* OptionalOutput) const
{
	auto bResult = false;

	const auto Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this);

	if (OwnerClass != nullptr && OwnerClass->ClassGeneratedBy != Blueprint)
	{
		bResult = true;

		if (OptionalOutput != nullptr)
		{
			OptionalOutput->AddUnique(OwnerClass);
		}
	}

	for (const auto& Description : CachedPins)
	{
		if (const auto Struct = Cast<UStruct>(Description.PinType.PinSubCategoryObject.Get()))
		{
			bResult = true;

			if (OptionalOutput != nullptr)
			{
				OptionalOutput->AddUnique(Struct);
			}
		}
	}

	const auto bSuperResult = Super::HasExternalDependencies(OptionalOutput);

	return bSuperResult || bResult;
}

